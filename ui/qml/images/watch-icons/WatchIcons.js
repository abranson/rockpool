function fileForCode(code) {
    if (!code) return "NOTIFICATION_GENERIC.svg";
    var key = String(code);
    var prefix = "system://images/";
    if (key.indexOf(prefix) === 0) key = key.substring(prefix.length);
    if (Object.prototype.hasOwnProperty.call(unavailableCodes, key)) return null;
    if (Object.prototype.hasOwnProperty.call(filesByCode, key)) return filesByCode[key];
    return "NOTIFICATION_GENERIC.svg";
}
